package com.honeytrace.report;

import java.io.ByteArrayOutputStream;
import java.util.List;

import com.honeytrace.entity.Attacker;

import com.itextpdf.text.Document;
import com.itextpdf.text.Font;
import com.itextpdf.text.FontFactory;
import com.itextpdf.text.Paragraph;

import com.itextpdf.text.pdf.PdfPTable;
import com.itextpdf.text.pdf.PdfWriter;

public class PdfReportGenerator {

    public static byte[] generate(List<Attacker> attackers)
            throws Exception {

        ByteArrayOutputStream out =
                new ByteArrayOutputStream();

        Document document =
                new Document();

        PdfWriter.getInstance(document, out);

        document.open();

        Font title =
                FontFactory.getFont(
                        FontFactory.HELVETICA_BOLD,
                        20);

        document.add(new Paragraph(
                "HoneyTrace Security Report",
                title));

        document.add(new Paragraph(" "));

        document.add(new Paragraph(
                "Generated by HoneyTrace SOC"));

        document.add(new Paragraph(
                "--------------------------------------"));

        document.add(new Paragraph(
                "Total Attackers : " + attackers.size()));

        document.add(new Paragraph(" "));

        PdfPTable table =
                new PdfPTable(5);

        table.setWidthPercentage(100);

        table.addCell("IP Address");
        table.addCell("Country");
        table.addCell("City");
        table.addCell("Risk");
        table.addCell("Last Seen");

        for (Attacker a : attackers) {

            table.addCell(a.getIpAddress());

            table.addCell(
                    a.getCountry() == null ?
                    "Unknown" :
                    a.getCountry());

            table.addCell(
                    a.getCity() == null ?
                    "Unknown" :
                    a.getCity());

            table.addCell(
                    String.valueOf(a.getRiskScore()));

            table.addCell(
                    String.valueOf(a.getLastSeen()));
        }

        document.add(table);

        document.close();

        return out.toByteArray();
    }

}